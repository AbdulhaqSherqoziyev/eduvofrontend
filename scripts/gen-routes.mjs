#!/usr/bin/env node
/**
 * Generates src/lib/routing/routes.generated.ts — the URL patterns of every page in the two root
 * layouts. The middleware uses them only to answer unknown URLs with HTTP 404 (Next 14.2 cannot
 * SSR notFound() when the app has two root layouts, so the catch-all pages render the 404 UI and
 * the status comes from the middleware). Runs before `dev` and `build`; `--check` fails when the
 * committed file is stale.
 */
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const APP = join(root, 'src', 'app');
const OUT = join(root, 'src', 'lib', 'routing', 'routes.generated.ts');

function pages(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) {
      if (name.startsWith('_') || name.startsWith('@')) continue; // private folders, parallel slots
      out.push(...pages(p));
    } else if (/^(page|route)\.(tsx?|jsx?)$/.test(name)) {
      out.push(relative(APP, dir));
    }
  }
  return out;
}

/** route dir → anchored regex source for the public pathname */
function toPattern(dirRel, dropPrefix) {
  let segs = dirRel.split(sep).filter(Boolean);
  segs = segs.filter((s) => !/^\(.*\)$/.test(s)); // route groups do not appear in the URL
  if (dropPrefix) segs = segs.slice(dropPrefix);
  if (segs.some((s) => /^\[\.\.\.missing\]$/.test(s))) return null; // the 404 catch-alls themselves
  let re = '';
  for (const s of segs) {
    if (/^\[\[\.\.\..+\]\]$/.test(s)) re += '(?:/.*)?';
    else if (/^\[\.\.\..+\]$/.test(s)) re += '/.+';
    else if (/^\[.+\]$/.test(s)) re += '/[^/]+';
    else re += '/' + s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  }
  return `^${re}/?$`;
}

const erpDir = join(APP, '(erp)');
const mockDir = join(APP, '(mock)', 'm', '[lang]');
const erp = pages(erpDir).map((d) => toPattern(d)).filter(Boolean);
// mock pages: path after /m/[lang] (the locale segment is checked separately)
const mock = existsSync(mockDir) ? pages(mockDir).map((d) => toPattern(d, 2)).filter(Boolean) : [];
const uniq = (a) => [...new Set(a)].sort();

/** every file under public/ as a URL path, plus the root route handlers (robots.txt, sitemap.xml) */
function files(dir, base = '') {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...files(p, `${base}/${name}`));
    else out.push(`${base}/${name}`);
  }
  return out;
}
const PUBLIC = join(root, 'public');
const rootHandlers = readdirSync(APP).filter((n) => /\.[a-z0-9]+$/i.test(n) && existsSync(join(APP, n, 'route.ts'))).map((n) => `/${n}`);
const publicFiles = [...(existsSync(PUBLIC) ? files(PUBLIC) : []), ...rootHandlers];

const src = `/* GENERATED by scripts/gen-routes.mjs — do not edit. */
/** Every ERP page (src/app/(erp)), as anchored pathname regex sources. */
export const ERP_ROUTES: readonly string[] = ${JSON.stringify(uniq(erp), null, 2)};
/** Every mock-site page under /{lang} (src/app/(mock)/m/[lang]); '^/?$' is the locale home. */
export const MOCK_ROUTES: readonly string[] = ${JSON.stringify(uniq(mock), null, 2)};
/** Files served as-is (public/ and root route handlers): any other path with a file extension is a 404. */
export const PUBLIC_FILES: readonly string[] = ${JSON.stringify(uniq(publicFiles), null, 2)};
`;

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== src) {
    console.error('routes.generated.ts is stale — run: node scripts/gen-routes.mjs');
    process.exit(1);
  }
  console.log('routes.generated.ts is up to date');
} else {
  writeFileSync(OUT, src);
  console.log(`routes.generated.ts: ${erp.length} ERP, ${mock.length} mock routes, ${publicFiles.length} files`);
}
